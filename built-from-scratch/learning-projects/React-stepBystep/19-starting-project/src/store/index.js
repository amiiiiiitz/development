// });
const store = configureStore({
  reducer: {
    counter: counterSlice.reducer,
    auth: authSlice.reducer,
  },
});

export const counterActions = counterSlice.actions; // this is how we can access the action creators generated by createSlice. when we define reducers in createSlice, it automatically generates action creators for each reducer function. these action creators are available as properties on the counterSlice.actions object. so if we have a reducer called increment, we can access the corresponding action creator using counterSlice.actions.increment. this action creator is a function that returns an action object with the correct type and payload (if needed) for that specific action. by using these generated action creators, we can easily dispatch actions to the store without having to manually create action objects or worry about typos in the action types. it provides a convenient and error-free way to dispatch actions in our application.

export const authActions = authSlice.actions;
export default store;
