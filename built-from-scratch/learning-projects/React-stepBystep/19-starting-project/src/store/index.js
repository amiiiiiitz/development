import { configureStore, createSlice } from "@reduxjs/toolkit";

const initialCounterState = { counter: 0, showCounter: true };

const counterSlice = createSlice({
  name: "counter",
  initialState: initialCounterState,
  reducers: {
    increment(state) {
      state.counter++; // here we cant also allow mutate the state but redux toolkit uses immer library under the hood, which allows us to write "mutating" logic in reducers. it does this by creating a draft state that we can modify directly, and then it produces a new immutable state based on the changes we made to the draft. so when we write state.counter++, we are actually modifying the draft state, and immer takes care of creating a new state object with the updated counter value while keeping the rest of the state unchanged. this makes our code more concise and easier to read, while still adhering to the principles of immutability in redux.
    },
    decrement(state) {
      state.counter--;
    },
    increase(state, action) {
      state.counter = state.counter + action.payload; // Using payload is the standard and default way in Redux Toolkit to send extra data with an action. When you dispatch an action like counterActions.increase(5), the value 5 automatically becomes action.payload. You must use action.payload in the reducer—using names like action.amount or others will not work unless you manually structure the action yourself
    },
    toggleCounter(state) {
      state.showCounter = !state.showCounter;
    },
  },
});

const initialAuthState = { isAuthenticated: false };
const authSlice = createSlice({
  name: "Authentication",
  initialState: initialAuthState,
  reducers: {
    login(state) {
      state.isAuthenticated = true;
    },
    logout(state) {
      state.isAuthenticated = false;
    },
  },
});



